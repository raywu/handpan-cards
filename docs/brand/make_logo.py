"""Generate the Handpan Theory logo set as SVG, redrawn from measurements of the brand board.

Usage: python3 docs/brand/make_logo.py docs/brand/logo
Needs fonttools. One geometry (GEOMETRY) for the mark; variants differ only in colour and effects.
GEOMETRY is printed by docs/brand/redraw/derive_geometry.py from the measured landmarks; change the
measurements or the fits there, never these numbers by hand. Units U: 100 U = half the distance
between the rim's two lens points, origin at their midpoint, y down. Plan: docs/plans/2026-10-31-logo-redraw.md.
Wordmark and tagline are outlined from tools/fonts (Marcellus, Nunito Sans SemiBold).
"""
import math, os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

FONTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools", "fonts")

TEAL, GOLD, WARM = "#44E0D8", "#F5C78E", "#F8EDD9"
BG, SURFACE, INK, PAPER = "#0F0E0B", "#1A1814", "#0F0E0B", "#F6F4ED"
SINGLE = "#E6C99B"
TAGLINE = "CHORDS & PROGRESSIONS"

# generated by docs/brand/redraw/derive_geometry.py
GEOMETRY = {"lens":[[-100.0,1.9],[100.0,-1.9]],"dome":[[-100.0,1.9],[-72.62,-24.49],[-37.36,-47.06],[0.0,-47.77],[37.36,-48.48],[72.62,-27.24],[100.0,-1.9]],"rim":[[-100.0,1.9],[-81.41,12.84],[-34.56,18.48],[0.0,17.82],[34.56,17.17],[81.41,9.75],[100.0,-1.9]],"shell":[[-100.0,1.9],[-78.2,14.83],[-29.21,31.94],[0.0,31.39],[29.21,30.83],[78.2,11.86],[100.0,-1.9]],"ding":[1.12,-40.3,22.36,7.29],"fields":[[-60.14,-13.27,6.81,4.08,-32],[-33.88,-7.44,6.81,5.83,-14],[2.09,-4.52,7.39,7.58,0],[39.04,-6.76,6.81,5.83,14],[66.75,-14.73,6.81,4.08,32]],"orbit":[5.2,-5.79,130.29,32.86,16.4],"teal_dot":[-105.93,41.47,9.14],"gold_dot":[111.28,-55.37,8.26],"rings":{"inner":[5.1,-2.77,88.09,80.31],"middle":[6.47,-4.72,105.49,97.52],"outer":[7.44,-6.47,122.99,114.73]},"ring_tilt":9.8,"ring_width":{"inner":1.56,"middle":1.46,"outer":1.17},"lobes":[["inner",55,215,[[55,1.0,0],[87.0,0.0,0.74],[119.0,0.0,0.93],[151.0,0.0,0.92],[183.0,0.0,0.69],[215,0.0,0]]],["inner",220,360,[[220,0.0,0],[248.0,0.0,0.42],[276.0,0.23,0.79],[304.0,0.75,0.93],[332.0,0.79,0.67],[360,0.92,0]]],["middle",65,205,[[65,0.39,0],[93.0,0.06,0.45],[121.0,0.05,0.71],[149.0,0.0,0.62],[177.0,0.0,0.52],[205,0.0,0]]],["middle",220,380,[[220,0.0,0],[252.0,0.0,0.2],[284.0,0.35,0.58],[316.0,0.92,0.78],[348.0,1.0,0.29],[380,1.0,0]]],["outer",0,35,[[0,1.0,0],[7.0,1.0,0.13],[14.0,1.0,0.32],[21.0,1.0,0.4],[28.0,1.0,0.16],[35,1.0,0]]],["outer",105,190,[[105,0.04,0],[122.0,0.0,0.26],[139.0,0.0,0.24],[156.0,0.0,0.19],[173.0,0.0,0.16],[190,0.0,0]]]],"stroke":{"pan":2.92,"orbit":2.53,"field":1.75}}

G = GEOMETRY
INKS = {"single": SINGLE, "mono-dark": PAPER, "mono-light": INK}
SMALL = {"stroke": 3.2, "dot": 1.6, "field_dot": 6.0}   # mark-small: heavier strokes, bigger dots, fields as dots, no rim line


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def P(p):
    return f"{f(p[0])} {f(p[1])}"


def ell_pt(cx, cy, a, b, tilt, deg):
    """point on an ellipse tilted `tilt` degrees (rising to the right); deg counted y-up"""
    th, t = math.radians(-tilt), math.radians(deg)
    x, y = a * math.cos(t), -b * math.sin(t)
    return cx + x * math.cos(th) - y * math.sin(th), cy + x * math.sin(th) + y * math.cos(th)


def curve(name):
    p = G[name]
    return f"M{P(p[0])} C{P(p[1])} {P(p[2])} {P(p[3])} C{P(p[4])} {P(p[5])} {P(p[6])}"


def silhouette():
    d, s = G["dome"], G["shell"]
    return (curve("dome") + f" C{P(s[5])} {P(s[4])} {P(s[3])} C{P(s[2])} {P(s[1])} {P(s[0])}Z")


def orbit_half(front):
    cx, cy, a, b, tilt = G["orbit"]
    l = ell_pt(cx, cy, a, b, tilt, 180)
    r = ell_pt(cx, cy, a, b, tilt, 0)
    # deg counted y-up: the front (lower) half runs 180 -> 270 -> 360, counterclockwise on screen (sweep 0)
    return f"M{P(l)} A{f(a)} {f(b)} {f(-tilt)} 0 {0 if front else 1} {P(r)}"


def lobe(ring, a0, a1, stops, uid, j, ink=None, opacity_scale=1.0):
    cx, cy, a, b = G["rings"][ring]
    tilt = G["ring_tilt"]
    p0, p1 = ell_pt(cx, cy, a, b, tilt, a0), ell_pt(cx, cy, a, b, tilt, a1)
    d = f"M{P(p0)} A{f(a)} {f(b)} {f(-tilt)} {1 if a1 - a0 > 180 else 0} 0 {P(p1)}"
    dx, dy = p1[0] - p0[0], p1[1] - p0[1]
    st = []
    for ang, warm, op in stops:
        q = ell_pt(cx, cy, a, b, tilt, ang)
        off = min(1, max(0, ((q[0] - p0[0]) * dx + (q[1] - p0[1]) * dy) / (dx * dx + dy * dy)))
        if ink:
            col = ink
        else:
            col = "#%02X%02X%02X" % tuple(round(t * (1 - warm) + g * warm) for t, g in
                                          zip((0x44, 0xE0, 0xD8), (0xF5, 0xC7, 0x8E)))
        st.append((off, col, op * opacity_scale))
    st.sort()
    gid = f"{uid}L{j}"
    grad = (f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{f(p0[0])}" y1="{f(p0[1])}" '
            f'x2="{f(p1[0])}" y2="{f(p1[1])}">'
            + "".join(f'<stop offset="{o:.3f}" stop-color="{c}" stop-opacity="{op:.2f}"/>' for o, c, op in st)
            + "</linearGradient>")
    return grad, f'<path d="{d}" stroke="url(#{gid})" stroke-width="{G["ring_width"][ring]}" fill="none" stroke-linecap="round"/>'


def mark(v, uid, small=False):
    """Mark body in U coordinates. v: full | single | mono-dark | mono-light."""
    ink = INKS.get(v)
    full = v == "full" and not small
    k = SMALL["stroke"] if small else 1.0
    sw, so, sf = G["stroke"]["pan"] * k, G["stroke"]["orbit"] * k, G["stroke"]["field"]
    tx, ty, tr = G["teal_dot"]
    gx, gy, gr = G["gold_dot"]
    if small:
        tr, gr = tr * SMALL["dot"], gr * SMALL["dot"]
    defs = [f'<mask id="{uid}m" maskUnits="userSpaceOnUse" x="-200" y="-200" width="400" height="400">'
            f'<rect x="-200" y="-200" width="400" height="400" fill="#fff"/>'
            f'<path d="{silhouette()}" fill="#000" stroke="#000" stroke-width="{f(sw + 2)}"/></mask>']
    if full:
        defs.append(f'<linearGradient id="{uid}o" gradientUnits="userSpaceOnUse" x1="{f(tx)}" y1="{f(ty)}" x2="{f(gx)}" y2="{f(gy)}">'
                    f'<stop offset="0" stop-color="{TEAL}"/><stop offset=".22" stop-color="{WARM}"/>'
                    f'<stop offset=".78" stop-color="{WARM}"/><stop offset="1" stop-color="{GOLD}"/></linearGradient>')
        defs.append(f'<filter id="{uid}g" x="-30%" y="-30%" width="160%" height="160%"><feGaussianBlur stdDeviation="2.1" result="b"/>'
                    f'<feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge></filter>')
        defs.append(f'<filter id="{uid}s" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="1.2" result="b"/>'
                    f'<feComponentTransfer in="b" result="c"><feFuncA type="linear" slope=".55"/></feComponentTransfer>'
                    f'<feMerge><feMergeNode in="c"/><feMergeNode in="SourceGraphic"/></feMerge></filter>')
        defs.append(f'<filter id="{uid}b" x="-100%" y="-100%" width="300%" height="300%"><feGaussianBlur stdDeviation="4.9"/></filter>')
        orbit_ink, pan_ink, teal, gold_core = f"url(#{uid}o)", WARM, TEAL, WARM
    else:
        orbit_ink = pan_ink = teal = gold_core = ink
    glow = f' filter="url(#{uid}g)"' if full else ""
    soft = f' filter="url(#{uid}s)"' if full else ""
    body = []
    if not small:
        paths = []
        for j, (ring, a0, a1, stops) in enumerate(G["lobes"]):
            g_, p_ = lobe(ring, a0, a1, stops, uid, j, None if full else ink, 1.0 if full else 0.85)
            defs.append(g_); paths.append(p_)
        body.append(f'<g mask="url(#{uid}m)"{glow}>{"".join(paths)}</g>')
    body.append(f'<path d="{orbit_half(False)}" fill="none" stroke="{orbit_ink}" stroke-width="{f(so)}" '
                f'stroke-linecap="round" mask="url(#{uid}m)"/>')
    dx, dy, drx, dry = G["ding"]
    # small: the rim's front edge merges with the bottom shell at icon sizes, so it is left out
    pan = [f'<path d="{curve("shell")}"/>'] + ([] if small else [f'<path d="{curve("rim")}"/>']) + [f'<path d="{curve("dome")}"/>',
           f'<ellipse cx="{f(dx)}" cy="{f(dy)}" rx="{f(drx)}" ry="{f(dry)}"/>']
    if small:
        dots = "".join(f'<circle cx="{f(x)}" cy="{f(y)}" r="{SMALL["field_dot"]}" fill="{pan_ink}" stroke="none"/>'
                       for x, y, *_ in G["fields"][1:4])
    else:
        dots = (f'<g stroke-width="{f(sf)}">' + "".join(
            f'<ellipse cx="{f(x)}" cy="{f(y)}" rx="{f(rx)}" ry="{f(ry)}" transform="rotate({rot} {f(x)} {f(y)})"/>'
            for x, y, rx, ry, rot in G["fields"]) + "</g>")
    body.append(f'<g fill="none" stroke="{pan_ink}" stroke-width="{f(sw)}" stroke-linecap="round" '
                f'stroke-linejoin="round"{soft}>{"".join(pan)}{dots}</g>')
    body.append(f'<path d="{orbit_half(True)}" fill="none" stroke="{orbit_ink}" stroke-width="{f(so)}" stroke-linecap="round"{glow}/>')
    if full:
        body.append(f'<circle cx="{f(tx)}" cy="{f(ty)}" r="{f(tr + 5)}" fill="{TEAL}" opacity=".35" filter="url(#{uid}b)"/>')
        body.append(f'<circle cx="{f(gx)}" cy="{f(gy)}" r="{f(gr + 5)}" fill="{GOLD}" opacity=".35" filter="url(#{uid}b)"/>')
    body.append(f'<circle cx="{f(tx)}" cy="{f(ty)}" r="{f(tr)}" fill="{teal}"/>')
    body.append(f'<circle cx="{f(gx)}" cy="{f(gy)}" r="{f(gr)}" fill="{gold_core}"/>')
    return "<defs>" + "".join(defs) + "</defs>" + "".join(body)


def bbox(small=False):
    """Bounding box (x, y, w, h) in U of everything the mark draws, plus a 5 U margin."""
    xs, ys = [], []
    def add(x, y, r=0):
        xs.extend([x - r, x + r]); ys.extend([y - r, y + r])
    cx, cy, a, b, tilt = G["orbit"]
    for d in range(0, 360, 2):
        add(*ell_pt(cx, cy, a, b, tilt, d), G["stroke"]["orbit"] * (SMALL["stroke"] if small else 1))
    k = SMALL["dot"] if small else 1.0
    add(*G["teal_dot"][:2], G["teal_dot"][2] * k); add(*G["gold_dot"][:2], G["gold_dot"][2] * k)
    for key in ("dome", "shell"):
        for p in G[key]:
            add(*p, G["stroke"]["pan"] * (SMALL["stroke"] if small else 1))
    if not small:
        for ring, a0, a1, _ in G["lobes"]:
            rx, ry, ra, rb = G["rings"][ring]
            for i in range(21):
                add(*ell_pt(rx, ry, ra, rb, G["ring_tilt"], a0 + (a1 - a0) * i / 20), 1)
    m = 5
    return min(xs) - m, min(ys) - m, max(xs) - min(xs) + 2 * m, max(ys) - min(ys) + 2 * m


# ---- outlined text ----------------------------------------------------------
class Face:
    def __init__(self, fn):
        self.f = TTFont(os.path.join(FONTS, fn))
        self.gs = self.f.getGlyphSet()
        self.cmap = self.f.getBestCmap()
        self.upm = self.f["head"].unitsPerEm
        self.hmtx = self.f["hmtx"]
        kern = {}
        if "kern" in self.f:
            for t in self.f["kern"].kernTables:
                kern.update(t.kernTable)
        self.kern = kern

    def width(self, s, size, track=0):
        w, prev = 0, None
        for ch in s:
            g = self.cmap[ord(ch)]
            if prev:
                w += self.kern.get((prev, g), 0)
            w += self.hmtx[g][0]
            prev = g
        return w * size / self.upm + track * size * (len(s) - 1)

    def path(self, s, x, y, size, track=0):
        k = size / self.upm
        pen = SVGPathPen(self.gs)
        cx, prev = 0, None
        for ch in s:
            g = self.cmap[ord(ch)]
            if prev:
                cx += self.kern.get((prev, g), 0)
            tp = TransformPen(pen, (k, 0, 0, -k, x + cx * k, y))
            self.gs[g].draw(tp)
            cx += self.hmtx[g][0] + track * self.upm
            prev = g
        return pen.getCommands()

MARC = Face("Marcellus-Regular.ttf")
NUNI = Face("NunitoSans-SemiBold.ttf")


def words(x, y, size, color, tag_color, align="left"):
    """Wordmark at baseline y, tagline under it fitted to the wordmark's width."""
    wm = "Handpan Theory"
    w = MARC.width(wm, size)
    ts = size * 0.3
    raw = NUNI.width(TAGLINE, ts)
    track = (w - raw) / (ts * (len(TAGLINE) - 1))
    track = max(0.12, min(track, 0.42))
    tw = NUNI.width(TAGLINE, ts, track)
    x0 = x - w / 2 if align == "center" else x
    tx = x0 + (w - tw) / 2
    return (f'<path d="{MARC.path(wm, x0, y, size)}" fill="{color}"/>'
            f'<path d="{NUNI.path(TAGLINE, tx, y + size * 0.62, ts, track)}" fill="{tag_color}"/>'), w


def svg(w, h, body, title, bg=None, rx=0):
    b = f'<rect width="{f(w)}" height="{f(h)}" rx="{rx}" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {f(w)} {f(h)}" width="{round(w)}" height="{round(h)}" '
            f'role="img" aria-label="{title}"><title>{title}</title>{b}{body}</svg>\n')


def placed(v, uid, x, y, height, small=False):
    """The mark scaled to `height` px with its top-left corner at (x, y); returns (markup, width)."""
    bx, by, bw, bh = bbox(small)
    k = height / bh
    return (f'<g transform="translate({f(x - bx * k)} {f(y - by * k)}) scale({k:.5f})">{mark(v, uid, small)}</g>', bw * k)


def main(out):
    os.makedirs(out, exist_ok=True)
    write = lambda name, s: open(os.path.join(out, name), "w").write(s)
    title = "Handpan Theory"
    for v in ("full", "single", "mono-dark", "mono-light"):
        bx, by, bw, bh = bbox()
        write(f"mark-{v}.svg", svg(bw * 2, bh * 2, placed(v, v[0] + "m", 0, 0, bh * 2)[0], title))
    bx, by, bw, bh = bbox(True)
    write("mark-small.svg", svg(bw * 2, bh * 2, placed("single", "sm", 0, 0, bh * 2, True)[0], title))

    TXT = {"full": (PAPER, "#A9A39A"), "single": (SINGLE, "#A9A39A"),
           "mono-dark": (PAPER, PAPER), "mono-light": (INK, INK)}
    for v, (c1, c2) in TXT.items():
        # horizontal: mark 3.2 x the wordmark size tall, text block centred on it
        size, mh, pad = 54, 172, 12
        m, mw = placed(v, "h" + v[0], pad, pad, mh)
        t, tw = words(pad + mw + 26, pad + mh / 2 + size * 0.12, size, c1, c2)
        write(f"lockup-horizontal-{v}.svg", svg(pad + mw + 26 + tw + pad + 12, mh + 2 * pad, m + t, title))
        # stacked: mark 0.9 x the wordmark's width, centred over it
        size = 72
        t, tw = words(0, 0, size, c1, c2, "center")
        bx, by, bw, bh = bbox()
        mw = tw * 0.9; mh = mw * bh / bw
        W = tw + 80
        m, _ = placed(v, "s" + v[0], (W - mw) / 2, 16, mh)
        base = 16 + mh + size * 0.95
        write(f"lockup-stacked-{v}.svg", svg(W, base + size * 0.62 + 30, m + f'<g transform="translate({f(W / 2)} {f(base)})">{t}</g>', title))

    # app icons, 1024 square, iOS-like corner; the mark spans 80% of the width
    for name, v, bgc in (("full", "full", SURFACE), ("single", "single", SURFACE), ("mono", "mono-light", PAPER)):
        bx, by, bw, bh = bbox()
        mw = 1024 * 0.8; mh = mw * bh / bw
        m, _ = placed(v, "i" + name[0], (1024 - mw) / 2, (1024 - mh) / 2, mh)
        write(f"app-icon-{name}.svg", svg(1024, 1024, m, title, bgc, 230))
    print("ok", sorted(os.listdir(out)))


if __name__ == "__main__":
    main(sys.argv[1])
